import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const outputDirectory = process.argv[2]
  ? resolve(process.argv[2])
  : fileURLToPath(new URL("../out/", import.meta.url));
const precacheExtensions = new Set([
  ".css", ".gz", ".html", ".ico", ".js", ".json", ".mjs", ".png", ".svg", ".txt", ".wasm", ".webmanifest", ".woff", ".woff2",
]);

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...await collectFiles(fullPath));
    } else if (entry.isFile() && entry.name !== "sw.js") {
      const extension = entry.name.slice(entry.name.lastIndexOf(".")).toLowerCase();
      if (precacheExtensions.has(extension)) files.push(fullPath);
    }
  }
  return files;
}

const files = (await collectFiles(outputDirectory)).sort();
if (!files.some((file) => relative(outputDirectory, file) === "index.html")) {
  throw new Error("Static export is missing index.html; service worker was not generated.");
}

const digest = createHash("sha256");
const urls = [];
for (const file of files) {
  const path = relative(outputDirectory, file).split(sep).map(encodeURIComponent).join("/");
  const content = await readFile(file);
  digest.update(path).update("\0").update(content).update("\0");
  urls.push(`./${path}`);
}

const cacheName = `noor-note-shell-${digest.digest("hex").slice(0, 20)}`;
const serviceWorker = `// Generated from the static export. Do not edit this file by hand.
const CACHE_PREFIX = "noor-note-shell-";
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(urls)};
const SCOPE = self.registration.scope;
const STATIC_PATHS = new Set(PRECACHE_URLS.map((path) => new URL(path, SCOPE).pathname));

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) =>
      cache.addAll(PRECACHE_URLS.map((path) => new URL(path, SCOPE).href)),
    ),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then(async (names) => {
      await Promise.all(names
        .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
        .map((name) => caches.delete(name)));
      await self.clients.claim();
    }),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith((async () => {
      try {
        return await fetch(request);
      } catch {
        const cache = await caches.open(CACHE_NAME);
        const scopePath = new URL(SCOPE).pathname;
        const path = url.pathname.startsWith(scopePath)
          ? url.pathname.slice(scopePath.length).replace(/^\\/+/, "")
          : "";
        const candidates = path
          ? ["./" + path, "./" + path + ".html", "./" + path.replace(/\\/?$/, "/") + "index.html"]
          : ["./index.html"];
        candidates.push("./index.html");
        for (const candidate of candidates) {
          const cached = await cache.match(new URL(candidate, SCOPE).href);
          if (cached) return cached;
        }
        return Response.error();
      }
    })());
    return;
  }

  if (!STATIC_PATHS.has(url.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    return (await cache.match(new URL(url.pathname, url.origin).href)) ?? fetch(request);
  })());
});
`;

await writeFile(join(outputDirectory, "sw.js"), serviceWorker);
console.log(`Generated ${cacheName} with ${urls.length} static assets.`);
